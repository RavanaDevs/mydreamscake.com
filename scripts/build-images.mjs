// Builds responsive AVIF + WebP variants of every image in src/assets/images/.
//
//   src/assets/images/cake-hero.jpg
//     -> public/images/cake-hero-<hash>-480.avif, …-480.webp, …-768.avif, …
//     -> src/generated/images.ts (typed manifest used by <Picture>)
//
// Runs automatically before `npm run dev` and `npm run build`. File names carry a content
// hash, so replacing a photo produces new URLs and browsers never show a stale cached copy.
// Unchanged images are skipped, so repeat runs take well under a second.
//
// To add or replace a photo: drop it into src/assets/images/ (jpg, png or webp) and refer to
// it by file name without extension, e.g. <Picture image="cake-hero" … />.

import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCE_DIR = path.join(ROOT, "src/assets/images");
const OUTPUT_DIR = path.join(ROOT, "public/images");
const MANIFEST_FILE = path.join(ROOT, "src/generated/images.ts");
const PUBLIC_PATH = "/images";

/** Widths generated for photos. Widths above the source width are capped to it. */
const DEFAULT_WIDTHS = [480, 768, 1024, 1280, 1600];
/** Per-image widths, keyed by file name without extension. */
const WIDTH_OVERRIDES = { logo: [128, 256, 384] };
/** Width of the plain <img src> fallback (the closest generated width at or below it). */
const FALLBACK_WIDTH = 1024;

const ENCODERS = {
  avif: { quality: 55, effort: 4 },
  webp: { quality: 78, effort: 5 },
};
const SUPPORTED = new Set([".jpg", ".jpeg", ".png", ".webp"]);

const toHex = ({ r, g, b }) => `#${[r, g, b].map((c) => c.toString(16).padStart(2, "0")).join("")}`;

async function buildImage(file) {
  const name = path.parse(file).name;
  const input = await readFile(path.join(SOURCE_DIR, file));
  const hash = createHash("sha256")
    .update(input)
    .update(JSON.stringify(ENCODERS))
    .digest("hex")
    .slice(0, 8);

  const image = sharp(input);
  const { width, height } = await image.metadata();
  const { dominant } = await image.stats();
  const widths = [
    ...new Set((WIDTH_OVERRIDES[name] ?? DEFAULT_WIDTHS).map((w) => Math.min(w, width))),
  ];

  const outputs = [];
  const srcSet = {};
  for (const [format, options] of Object.entries(ENCODERS)) {
    srcSet[format] = [];
    for (const w of widths) {
      const fileName = `${name}-${hash}-${w}.${format}`;
      const target = path.join(OUTPUT_DIR, fileName);
      outputs.push(fileName);
      srcSet[format].push(`${PUBLIC_PATH}/${fileName} ${w}w`);
      if (!existsSync(target)) {
        await sharp(input)
          .resize({ width: w, withoutEnlargement: true })
          [format](options)
          .toFile(target);
      }
    }
  }

  const fallbackWidth = widths.filter((w) => w <= FALLBACK_WIDTH).at(-1) ?? widths[0];
  return {
    name,
    outputs,
    entry: {
      width,
      height,
      color: toHex(dominant),
      src: `${PUBLIC_PATH}/${name}-${hash}-${fallbackWidth}.webp`,
      srcSet: { avif: srcSet.avif.join(", "), webp: srcSet.webp.join(", ") },
    },
  };
}

async function main() {
  const started = performance.now();
  await mkdir(OUTPUT_DIR, { recursive: true });
  await mkdir(path.dirname(MANIFEST_FILE), { recursive: true });

  const files = (await readdir(SOURCE_DIR))
    .filter((f) => SUPPORTED.has(path.extname(f).toLowerCase()))
    .sort();
  const results = await Promise.all(files.map(buildImage));

  // Remove variants of images that were replaced or deleted.
  const expected = new Set(results.flatMap((r) => r.outputs));
  for (const existing of await readdir(OUTPUT_DIR)) {
    if (!expected.has(existing)) await rm(path.join(OUTPUT_DIR, existing));
  }

  const manifest = Object.fromEntries(results.map((r) => [r.name, r.entry]));
  const source = `// Generated by scripts/build-images.mjs. Do not edit: changes are overwritten.

export type GeneratedImage = {
  /** Intrinsic size of the source image, used to reserve layout space. */
  width: number;
  height: number;
  /** Dominant colour, shown while the image loads. */
  color: string;
  /** Fallback for browsers without <picture> support. */
  src: string;
  srcSet: { avif: string; webp: string };
};

export const images = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, GeneratedImage>;

export type ImageName = keyof typeof images;
`;
  const current = existsSync(MANIFEST_FILE) ? await readFile(MANIFEST_FILE, "utf8") : "";
  if (current !== source) await writeFile(MANIFEST_FILE, source);

  const ms = Math.round(performance.now() - started);
  console.log(`images: ${results.length} sources, ${expected.size} variants ready (${ms} ms)`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
