import type { ComponentProps } from "react";

import { images, type ImageName } from "@/generated/images";

type PictureProps = Omit<
  ComponentProps<"img">,
  "src" | "srcSet" | "sizes" | "width" | "height" | "alt" | "loading"
> & {
  image: ImageName;
  alt: string;
  /** How wide the image renders, e.g. "(min-width: 1024px) 50vw, 100vw". Picks the right file. */
  sizes: string;
  /** Load immediately with high priority. Use only for images visible on first paint. */
  priority?: boolean;
  /** Fill the box with the photo's dominant colour while it loads. Off for transparent images. */
  placeholder?: boolean;
};

/**
 * Responsive image served as AVIF, then WebP, at the size that fits the screen.
 * Variants are pre-generated by scripts/build-images.mjs (next/image optimisation
 * is unavailable in a static export). The <picture> wrapper uses `display: contents`,
 * so `className` styles the <img> exactly as if it stood alone.
 */
export function Picture({
  image,
  alt,
  sizes,
  priority = false,
  placeholder = true,
  style,
  ...imgProps
}: PictureProps) {
  const { width, height, color, src, srcSet } = images[image];

  return (
    <picture className="contents">
      <source type="image/avif" srcSet={srcSet.avif} sizes={sizes} />
      <source type="image/webp" srcSet={srcSet.webp} sizes={sizes} />
      <img
        src={src}
        alt={alt}
        width={width}
        height={height}
        loading={priority ? "eager" : "lazy"}
        fetchPriority={priority ? "high" : undefined}
        decoding="async"
        style={placeholder ? { backgroundColor: color, ...style } : style}
        {...imgProps}
      />
    </picture>
  );
}
