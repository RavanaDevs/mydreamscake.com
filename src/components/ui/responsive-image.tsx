import type { ComponentProps } from "react";

import type { GeneratedImage } from "@/generated/images";

export type ResponsiveImageProps = Omit<
  ComponentProps<"img">,
  "src" | "srcSet" | "sizes" | "width" | "height" | "alt" | "loading"
> & {
  image: GeneratedImage;
  alt: string;
  /** How wide the image renders, e.g. "(min-width: 1024px) 50vw, 100vw". Picks the right file. */
  sizes: string;
  /** Load immediately with high priority. Use only for images visible on first paint. */
  priority?: boolean;
  /** Fill the box with the photo's dominant colour while it loads. Off for transparent images. */
  placeholder?: boolean;
};

/**
 * Responsive WebP image. Sizes are pre-generated by scripts/build-images.mjs (next/image
 * optimisation is unavailable in a static export). Safe to use in client components: it takes
 * resolved image data rather than reading the image manifest.
 */
export function ResponsiveImage({
  image,
  alt,
  sizes,
  priority = false,
  placeholder = true,
  style,
  ...imgProps
}: ResponsiveImageProps) {
  return (
    // eslint-disable-next-line @next/next/no-img-element -- static export: sizes are pre-generated
    <img
      src={image.src}
      srcSet={image.srcSet}
      sizes={sizes}
      alt={alt}
      width={image.width}
      height={image.height}
      loading={priority ? "eager" : "lazy"}
      fetchPriority={priority ? "high" : undefined}
      decoding="async"
      style={placeholder ? { backgroundColor: image.color, ...style } : style}
      {...imgProps}
    />
  );
}
